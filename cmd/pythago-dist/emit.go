package main

import (
	"encoding/json"
	"fmt"
	"log"
	"os"
	"path/filepath"
)

// emit writes the registration file, a manifest and the PBS license notices.
func emit(o *options, licenses string, meta pbsMeta, shared bool) error {
	exports := ""
	if shared {
		// The C API comes from the shared object's exports; pythago_symtab lists the glue.
		exports = "\n\tpy.RegisterExports(SharedObjectExports(), SharedObjectExport)"
	}
	suffix := o.goos + "_" + o.goarch
	reg := fmt.Sprintf(`// Code generated by pythago-dist; DO NOT EDIT.

package %[1]s

import (
	_ "embed"

	"github.com/moriyoshi/pythago/py"
)

//go:embed stdlib_%[2]s.zip
var stdlibZip []byte

// Importing this package registers CPython %[3]s (%[4]s) for %[5]s with package py: the
// native image and the standard library.
func init() {
	py.RegisterImage(SymbolAddr0())%[6]s
	py.RegisterStdlibZip(stdlibZip)
}
`, o.pkg, suffix, meta.pyver(), o.variant, o.target, exports)
	if err := os.WriteFile(filepath.Join(o.out, "register_"+suffix+".go"), []byte(reg), 0o644); err != nil {
		return err
	}
	if err := writeManifest(o, meta); err != nil {
		return err
	}
	if dirExists(licenses) {
		if err := copyTree(licenses, filepath.Join(o.out, "licenses")); err != nil {
			return err
		}
	}
	log.Printf("generated package %s in %s", o.pkg, o.out)
	return nil
}

// writeManifest records what the package was generated from.
func writeManifest(o *options, meta pbsMeta) error {
	fields := map[string]string{
		"python": meta.pyver(), "variant": o.variant, "target": o.target,
		"pbs_release": o.release, "pbs_target": meta.target, "mode": o.mode,
	}
	if meta.glibcFloor != "" {
		fields["glibc_floor"] = meta.glibcFloor
	}
	manifest, _ := json.MarshalIndent(fields, "", "  ")
	return os.WriteFile(filepath.Join(o.out, "pythago-dist_"+o.goos+"_"+o.goarch+".json"), append(manifest, '\n'), 0o644)
}

func dirExists(p string) bool {
	st, err := os.Stat(p)
	return err == nil && st.IsDir()
}

func copyTree(src, dst string) error {
	return filepath.Walk(src, func(p string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(src, p)
		return copyFile(p, filepath.Join(dst, rel))
	})
}
