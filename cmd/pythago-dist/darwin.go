// compileDarwinGlue compiles the glue for a darwin target into one Mach-O object, which
// bao takes as the single object beside the dylib. Without a partial linker (ld64.lld
// has no -r) the sources are one translation unit; pythago_symtab is appended to it once
// a first compile has listed the pythago_* functions. The fusion's reader check
// (pythago_fusioncheck.c) needs CPython's internal headers, which elsewhere it includes
// in a translation unit of its own; here it comes last, with PYTHAGO_GLUE_UNITY, so that
// the other sources parse Python.h without the core defines.
func compileDarwinGlue(o *options, include string) (string, error) {
	if err := o.resolveSDK(); err != nil {
		return "", err
	}
	clang, err := o.darwinClang()
	if err != nil {
		return "", err
	}
	dir := filepath.Join(o.work, "glue")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	var unity bytes.Buffer
	unity.WriteString("/* Generated by pythago-dist: the glue as one translation unit. */\n")
	last := ""
	for _, name := range glueFiles(true) {
		data, _ := fs.ReadFile(glue.Sources, name)
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o644); err != nil {
			return "", err
		}
		if name == coreGlue {
			last = name
			continue
		}
		fmt.Fprintf(&unity, "#include %q\n", name)
	}
	if last != "" {
		fmt.Fprintf(&unity, "#define PYTHAGO_GLUE_UNITY 1\n#include %q\n", last)
	}
	compile := func(src []byte, obj string) error {
		if err := os.WriteFile(filepath.Join(dir, "unity.c"), src, 0o644); err != nil {
			return err
		}
		// Relative paths, run in o.work: the object does not depend on where it is built.
		args := append(o.clangTarget(), "-c", "-O2", "-fPIC", "-I"+include, "-I"+filepath.Join(include, "internal"),
			"-o", obj, filepath.Join("glue", "unity.c"))
		return execToolIn(o.work, clang, args...)
	}
	if err := compile(unity.Bytes(), filepath.Join("glue", "names.o")); err != nil {
		return "", err
	}
	names, err := machoFunctions(filepath.Join(dir, "names.o"), "pythago_")
	if err != nil {
		return "", err
	}
	unity.WriteString("\nconst struct { const char *name; void *addr; } pythago_symtab[] = {\n")
	for _, n := range names {
		fmt.Fprintf(&unity, "  {%q, (void *)%s},\n", n, n)
	}
	unity.WriteString("  {0, 0},\n};\n")
	log.Printf("pythago_symtab: %d symbols", len(names))
	if err := compile(unity.Bytes(), "glue.o"); err != nil {
		return "", err
	}
	return filepath.Join(o.work, "glue.o"), nil
}

// coreGlue is the glue source that includes CPython's internal headers.
const coreGlue = "pythago_fusioncheck.c"

// machoFunctions lists the external functions an object defines whose C names start with
// prefix (Mach-O names carry a leading underscore), in symbol-table order.
func machoFunctions(obj, prefix string) ([]string, error) {
	f, err := macho.Open(obj)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	if f.Symtab == nil {
		return nil, fmt.Errorf("%s: no symbol table", obj)
	}
	text := 0 // 1-based index of __TEXT,__text
	for i, sec := range f.Sections {
		if sec.Seg == "__TEXT" && sec.Name == "__text" {
			text = i + 1
		}
	}
	var out []string
	for _, s := range f.Symtab.Syms {
		const nExt, nType, nSect = 0x01, 0x0e, 0x0e
		name, ok := strings.CutPrefix(s.Name, "_")
		if ok && s.Type&nExt != 0 && s.Type&nType == nSect && int(s.Sect) == text && strings.HasPrefix(name, prefix) {
			out = append(out, name)
		}
	}
	return out, nil
}

// darwinClang is the clang for the darwin glue: the configured LLVM (-llvm,
// PYTHAGO_LLVM), else on a macOS host Xcode's, else the fetched LLVM (which needs -sdk).
func (o *options) darwinClang() (string, error) {
	if o.llvm == "" && os.Getenv("PYTHAGO_LLVM") == "" && runtime.GOOS == "darwin" {
		out, err := exec.Command("xcrun", "--sdk", "macosx", "--find", "clang").Output()
		if err != nil {
			return "", fmt.Errorf("xcrun --find clang: %w", err)
		}
		return strings.TrimSpace(string(out)), nil
	}
	if err := o.needLLVM(); err != nil {
		return "", err
	}
	return o.tool("clang"), nil
}

// resolveSDK defaults -sdk to xcrun's SDK on a macOS host.
func (o *options) resolveSDK() error {
	if o.sdk != "" {
		return nil
	}
	if runtime.GOOS != "darwin" {
		return fmt.Errorf("darwin targets built on %s need -sdk (a macOS SDK directory)", runtime.GOOS)
	}
	out, err := exec.Command("xcrun", "--sdk", "macosx", "--show-sdk-path").Output()
	if err != nil {
		return fmt.Errorf("xcrun --show-sdk-path: %w", err)
	}
	o.sdk = strings.TrimSpace(string(out))
	return nil
}
