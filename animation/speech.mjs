import { spawnSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import { movieDuration, movieFromArgs } from './subtitles.mjs';

// Sample a short RMS window around each timestamp. The result can be indexed
// directly by the playhead in the offline player and during frame capture.
export function speechTrack(audio, duration = movieDuration()) {
  const sampleRate = 8000;
  const rate = 50;
  const samplesPerLevel = sampleRate / rate;
  const result = spawnSync('ffmpeg', [
    '-v', 'error', '-nostdin', '-i', audio, '-map', '0:a:0', '-t', String(duration),
    '-ac', '1', '-ar', String(sampleRate), '-f', 's16le', 'pipe:1',
  ], { maxBuffer: Math.ceil(duration * sampleRate * 2) + 1024 * 1024 });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(result.stderr.toString().trim());

  const pcm = result.stdout;
  const sampleCount = pcm.length / 2;
  const levels = Array.from({ length: Math.ceil(sampleCount / samplesPerLevel) }, (_, i) => {
    const start = i * samplesPerLevel - samplesPerLevel / 2;
    let energy = 0;
    for (let j = Math.max(0, start); j < Math.min(sampleCount, start + samplesPerLevel); j++) {
      const sample = pcm.readInt16LE(j * 2);
      energy += sample * sample;
    }
    return Math.sqrt(energy / samplesPerLevel);
  });

  // Use voiced windows to set the scale, with a separate gate for quiet pauses.
  const peak = levels.reduce((max, level) => Math.max(max, level), 0);
  const voiced = levels.filter(level => level > peak * 0.04).sort((a, b) => a - b);
  const reference = voiced[Math.floor(voiced.length * 0.95)] ?? 1;
  const gate = reference * 0.08;
  const strengths = levels.map(level => Math.sqrt(Math.max(0, Math.min(1, (level - gate) / (reference - gate)))));
  const bytes = Buffer.from(strengths.map((level, i) => Math.round(255 * (
    0.16 * (strengths[i - 1] ?? 0) + 0.68 * level + 0.16 * (strengths[i + 1] ?? 0)
  ))));
  return { rate, levels: bytes.toString('base64') };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const audio = process.argv[2];
  if (!audio) throw new Error('Usage: node speech.mjs narration.wav [--movie introduction|internals|native]');
  const movie = movieFromArgs(process.argv.slice(3));
  const { rate, levels } = speechTrack(audio, movieDuration(movie));
  const lines = levels.match(/.{1,100}/g) ?? [];
  const condition = movie === 'introduction' ? '' : `if (window.PYTHAGO_MOVIE === '${movie}') `;
  process.stdout.write(`// Generated by speech.mjs from the aligned narration.\n${condition}window.PYTHAGO_SPEECH ??= { rate: ${rate}, levels: \`\n${lines.join('\n')}\n\` };\n`);
}
